def present_cta_candidates(today=None):
    """当日有効なプレゼント1つ分の誘導投稿だけを返す（(key, [本文...]) / 開始前はNone）。"""
    p = current_present(today)
    if not p:
        return None
    return p["key"], list(PRESENT_CTA.get(p["key"], []))


