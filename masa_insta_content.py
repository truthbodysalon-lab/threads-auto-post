from __future__ import annotations

import re as _re_mod

_NUM = "①②③④"


def _insta_target(t):
    """対象の前に「インスタ運用で、」を付けて、何の話か（Instagram）を本文だけで分かるようにする。
    （Threadsの読み手が『何のコンセプト？』と迷わない／Instagramテーマ判定にも掛かる）"""
    if _re_mod.search(r"インスタ|Instagram|リール|ストーリーズ", t):
        return t
    return ("インスタ運用で、", "インスタで、")[sum(map(ord, t)) % 2] + t


def _comment(steps, today):
    lines = [f"{_NUM[i]} {s}" for i, s in enumerate(steps)]
    return "\n".join(lines) + f"\n\n今日は、{today}。"


def _post(body, steps, today):
    return body + "\n[COMMENT]\n" + _comment(steps, today)


