# 本文の型（{t}=対象 {hook}=1行目の断言 {items}=リスト {nitems}=①②③ {why}=理由1行 {maxim}=締めの格言）。
# 1行目は宛名だけにしない（uplink型）。対象は2行目に置く。
INSTA_GEN_STRUCTURES = [
    "{hook}\n{t}へ。\n\n{items}\n\n{why}\n{maxim}",
    "ぶっちゃけ、{hook}\n{t}は、まずこれだけ。\n\n{items}\n\n{why}\n{maxim}",
    "{hook}\n{t}は、この3つだけ。\n\n{nitems}\n\n{why}\n{maxim}",
    "{t}へ。\n{hook}\n\n{items}\n\n{why}\n{maxim}",
    "{hook}\n{t}なら、今日できる。\n\n{items}\n\n{why}\n{maxim}",
]


def build_gen_post(structure_idx, hurdle):
    t, q, c, steps, today, hook, items, maxim, why = hurdle
    t = _insta_target(t)
    body = INSTA_GEN_STRUCTURES[structure_idx % len(INSTA_GEN_STRUCTURES)].format(
        t=t, hook=hook, items="\n".join(items),
        nitems="\n".join(f"{_NUM[i]}{s}" for i, s in enumerate(items)), why=why, maxim=maxim)
    return _post(body, steps, today)



def _u(l1, l2, items, why, closer, numbered=False):
    """uplink型の本文: 1行目=断言 / 2行目=対象 / リスト3〜4行 / 締めの格言1行（質問で終わらない）。"""
    ls = [l1, l2, ""]
    ls += [f"{_NUM[i]}{s}" if numbered else s for i, s in enumerate(items)]
    ls += ["", why, closer]
    return "\n".join(ls)


