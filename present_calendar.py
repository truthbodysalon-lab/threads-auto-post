"""masa『今週のプレゼント』順番表リーダー（正本=present_calendar.json）。
2026-10-17: プレゼントを一気に出さず1期1つずつ出す（masa指示）。投稿は当期のプレゼント1つだけを誘導する。"""
import json
import random
from datetime import date, timedelta
from pathlib import Path

_CAL = Path(__file__).parent / "present_calendar.json"


def load_calendar() -> dict:
    return json.loads(_CAL.read_text(encoding="utf-8"))


def current_present(today=None, cal=None, pre_anchor_first=False):
    """today(date|ISO文字列|None)が属する期のプレゼントを返す。開始前ならNone。
    戻り値: {**present, period_start, period_end, cycle}"""
    cal = cal or load_calendar()
    if today is None:
        today = date.today()
    elif isinstance(today, str):
        today = date.fromisoformat(today[:10])
    anchor = date.fromisoformat(cal["anchor"])
    days = int(cal.get("days", 7))
    delta = (today - anchor).days
    if delta < 0:
        if not pre_anchor_first:
            return None
        delta = 0   # 投稿側: 開始日前は①(インスタ)の誘導を続ける（既に配布中のため）
    n = delta // days
    ps = cal["presents"]
    p = dict(ps[n % len(ps)])
    p["period_start"] = (anchor + timedelta(days=n * days)).isoformat()
    p["period_end"] = (anchor + timedelta(days=n * days + days - 1)).isoformat()
    p["cycle"] = n // len(ps)
    return p


