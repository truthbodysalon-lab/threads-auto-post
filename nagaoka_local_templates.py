def eligible(month: int) -> list[tuple[str, str]]:
    """その月に出してよい原稿 (id, 本文) の一覧。"""
    return [(i, t) for i, m, t in NAGAOKA_LOCAL_TRUTH if m is None or month in m]


_LOCAL_TEXTS = {t.strip() for _, _, t in NAGAOKA_LOCAL_TRUTH}


def is_local_post(text: str) -> bool:
    """この型の投稿か（このファイルの原稿と一致するか）。verify・テスト用。"""
    if not text:
        return False
    return text.strip() in _LOCAL_TEXTS


def validate(text: str) -> list[str]:
    """型の決まりを満たさない点を返す（空なら合格）。"""
    reasons = []
    parts = [p.strip() for p in text.split("[COMMENT]")]
    if len(parts) != 3:
        return [f"ツリーが{len(parts) - 1}本（2本にする）"]
    parent = [l for l in parts[0].split("\n") if l.strip()]
    if not parent or not parent[0].startswith("長岡市"):
        reasons.append("親投稿が「長岡市」で始まっていない")
    if len(parent) != 2:
        reasons.append(f"親投稿が{len(parent)}行（2行にする）")
    if not parts[0].rstrip().endswith(("？", "?")):
        reasons.append("親投稿が問いかけで終わっていない")
    for n, body in enumerate(parts[1:], 1):
        lines = [l for l in body.split("\n") if l.strip()]
        if not 2 <= len(lines) <= 3:
            reasons.append(f"ツリー{n}が{len(lines)}行（2〜3行にする）")
    if parts[2].rstrip().endswith(("？", "?")):
        reasons.append("最後が質問で終わっている")
    if "http" in text or "#" in text or "予約" in text:
        reasons.append("URL・ハッシュタグ・予約誘導が入っている")
    if max(len(l) for l in text.replace("[COMMENT]", "").split("\n")) > 34:
        reasons.append("1行が34字を超えている")
    return reasons
