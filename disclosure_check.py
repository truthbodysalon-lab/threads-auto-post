"""masa投稿の『自動投稿・AI投稿の開示』検出（2026-10-17 本人指示）。
なぜ: masaは「個人が自分で発信している」体で出す。投稿を AI/自動で出していると明かすと、
発信者の信頼と個人感が落ちる。AIの『使い方』を教える文は対象外（読者への助言は可）。
可: お店の作業をAIに任せる／返事の下書きはAIに頼む。不可: この投稿はAI・僕のSNSは自動・1日○本・誰も書いていない。"""
import re

_PATS = [
    r"自動投稿|自動で投稿|自動で発信|自動発信|全自動|完全自動|自動運用|自動でSNS|自動で回",
    r"(この|今読んでいる|いま読んでいる)(投稿|アカウント|発信|文章|SNS|スレッズ|Threads|ストーリー)[^。\n]{0,14}(AI|ＡＩ|自動|ロボ)",
    r"(僕|私|俺|ぼく|わたし)(の|が)[^。\n]{0,6}(投稿|SNS|発信|アカウント|Threads|スレッズ|インスタ|ストーリー|文章)[^。\n]{0,16}(AI|ＡＩ|自動|ほぼ全部|勝手に)",
    r"AIが[^。\n]{0,4}(書い|投稿し|発信し|出して|出し)(て)?(い)?(ます|ました|る)",   # 例: AIが書いています/AIが出しています
    r"AIが(毎朝|毎日|夕方)[^。\n]{0,16}(作っ|書い|投稿|公開|出し|見直し|確認|やっ|送っ)",
    r"AIの仕組みが送",
    r"(毎日|1日|一日)\s*[0-9０-９]+\s*(本|件|通)[^。\n]{0,6}(投稿|発信|出し|上げ|アップ|送)",
    r"誰も(書いて|触って|手を|打って|操作)|手を(動かして|触れて)(い)?ない|寝てる間に[^。\n]{0,8}(投稿|発信)",
    r"(全部|すべて|全て|ぜんぶ)(が|を|は)?\s*AI(が|に|で|です|だ)",
    r"(AI社員|AIスタッフ|AI部門|AI秘書|AI運用)",
    r"(YouTube|Kindle|動画|本)の?[^。\n]{0,6}(も|は)[^。\n]{0,4}AIが(作|書)",
    r"僕は(1本も|一本も)書いて",
    r"確認だけ自分でしています",
    r"毎朝、?AIが|AIが(前日|昨日)",
    r"(発信|投稿)も返事も、?(下書きは)?AI|この順番で任せました",
    r"閉店後に(SNS|投稿|発信)[^。\n]{0,10}(書く時間|時間)は[^。\n]{0,4}ゼロ",
    r"僕は[0-9１-９一]?[^。\n]{0,8}(1通ずつ|一通ずつ)送っていません",
    r"AIの仕事が止まったら",
    r"僕が毎朝やるのは、AIの案を選ぶだけ",
]
DISCLOSURE_RE = re.compile("|".join(f"(?:{p})" for p in _PATS))
# 読者への助言・AI臭を戒める文は除外
_ALLOW = re.compile(r"AIが書いたような|AIが書いた文|AIが書いたもの|AIが出した(文|答え)|AIが下書き")


def disclosure_reasons(text: str) -> list:
    t = text or ""
    out = []
    # 2026-10-17 本人決定: 強化書(有料)は投稿・プレゼント誘導で名前も出さない（販売はLINE育成配信Day6-7のみ）
    if "強化書" in t:
        out.append("有料教材(強化書)への言及は投稿では禁止")
    for m in DISCLOSURE_RE.finditer(t):
        ctx = t[max(0, m.start() - 4): m.end() + 6]
        if _ALLOW.search(ctx):
            continue
        out.append("自動投稿/AI投稿の開示: " + m.group(0)[:30])
    return out


def has_disclosure(text: str) -> bool:
    return bool(disclosure_reasons(text))
