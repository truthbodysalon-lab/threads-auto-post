TOPIC_COOLDOWN_DAYS = 3     # 同じ話題（2本目）は3日以上あける
REUSE_DAYS = 8              # 同じ原稿は8日出さない（duplicate_guard の7日＋1）

_BY_TEXT = {t.strip(): (i, topic) for i, topic, _, t in NAGAOKA_STORE_LOCAL}


def eligible(month: int) -> list[tuple[str, str, str]]:
    """その月に出してよい原稿 (id, 話題id, 本文)。"""
    return [(i, topic, t) for i, topic, m, t in NAGAOKA_STORE_LOCAL if m is None or month in m]


def topic_of(text: str) -> str | None:
    hit = _BY_TEXT.get((text or "").strip())
    return hit[1] if hit else None


def is_store_local_post(text: str) -> bool:
    return topic_of(text) is not None


def validate(text: str) -> list[str]:
    """型の決まりを満たさない点を返す（空なら合格）。"""
    reasons = []
    parts = [p.strip() for p in text.split("[COMMENT]")]
    if len(parts) != 2:
        return [f"ツリーが{len(parts) - 1}本（1本にする）"]
    parent = [l for l in parts[0].split("\n") if l.strip()]
    if len(parent) != 2:
        reasons.append(f"親投稿が{len(parent)}行（2行にする）")
    if not parts[0].rstrip().endswith(("？", "?")):
        reasons.append("親投稿が問いかけで終わっていない")
    tree = [l for l in parts[1].split("\n") if l.strip()]
    if not 2 <= len(tree) <= 3:
        reasons.append(f"ツリーが{len(tree)}行（2〜3行にする）")
    if parts[1].rstrip().endswith(("？", "?")):
        reasons.append("最後が質問で終わっている")
    if "http" in text or "#" in text or "予約" in text or "lin.ee" in text:
        reasons.append("URL・ハッシュタグ・予約誘導が入っている")
    if max(len(l) for l in text.replace("[COMMENT]", "").split("\n")) > 40:
        reasons.append("1行が40字を超えている")
    return reasons
